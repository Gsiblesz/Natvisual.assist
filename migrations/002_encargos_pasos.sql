-- Clientes con estado: activo, inactivo o archivado.
alter table cuentas add column if not exists estado text not null default 'activo';
alter table cuentas add column if not exists estado_desde timestamptz not null default now();

do $$
begin
  alter table cuentas add constraint cuentas_estado_check
    check (estado in ('activo', 'inactivo', 'archivado'));
exception when duplicate_object then null;
end $$;

-- Cada encargo (tarea) tiene un tipo que decide sus pasos.
alter table tareas add column if not exists tipo text not null default 'otro';

create table if not exists pasos (
  id integer generated by default as identity primary key,
  tarea_id integer not null references tareas (id) on delete cascade,
  orden integer not null,
  nombre text not null,
  fecha date,
  hecho_en timestamptz,
  creado_en timestamptz not null default now()
);

create index if not exists pasos_tarea_idx on pasos (tarea_id);

-- Las entregas que ya existían quedan con un solo paso.
insert into pasos (tarea_id, orden, nombre, fecha, hecho_en)
select t.id, 1, 'Hacer', t.fecha_entrega, case when t.estado = 'hecho' then now() end
from tareas t
where not exists (select 1 from pasos p where p.tarea_id = t.id);

-- Teléfonos que reciben el resumen de la mañana.
create table if not exists suscripciones (
  endpoint text primary key,
  p256dh text not null,
  auth text not null,
  creado_en timestamptz not null default now()
);

-- Ajustes internos (claves de notificación, último resumen enviado).
create table if not exists ajustes (
  clave text primary key,
  valor text not null
);
