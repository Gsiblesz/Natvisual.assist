create table if not exists cuentas (
  id integer generated by default as identity primary key,
  nombre_cliente text not null,
  creado_en timestamptz not null default now()
);

create table if not exists tareas (
  id integer generated by default as identity primary key,
  cuenta_id integer not null references cuentas (id) on delete cascade,
  titulo text not null,
  descripcion text not null default '',
  estado text not null default 'pendiente' check (estado in ('pendiente', 'en_progreso', 'hecho')),
  prioridad_cliente integer not null default 2 check (prioridad_cliente between 1 and 3),
  urgencia_humana integer not null default 2 check (urgencia_humana between 1 and 3),
  prioridad_modo text not null default 'cliente' check (prioridad_modo in ('cliente', 'humana')),
  fecha_entrega date,
  etiqueta text not null default '',
  google_event_id text,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

create table if not exists historial (
  id integer generated by default as identity primary key,
  tarea_id integer not null references tareas (id) on delete cascade,
  estado_anterior text,
  estado_nuevo text not null,
  nota text not null default '',
  creado_en timestamptz not null default now()
);

create table if not exists calendarios (
  cuenta_id integer primary key references cuentas (id) on delete cascade,
  proveedor text not null default 'ics' check (proveedor in ('ics', 'google')),
  correo_equipo text not null default '',
  google_calendar_id text not null default '',
  aviso_horas integer not null default 24 check (aviso_horas between 1 and 168),
  feed_token text not null unique,
  creado_en timestamptz not null default now()
);

create table if not exists avisos (
  id integer generated by default as identity primary key,
  cuenta_id integer not null references cuentas (id) on delete cascade,
  tarea_id integer references tareas (id) on delete set null,
  titulo text not null,
  canal text not null,
  estado text not null,
  detalle text not null default '',
  creado_en timestamptz not null default now()
);

create index if not exists tareas_cuenta_idx on tareas (cuenta_id);
create index if not exists tareas_fecha_idx on tareas (fecha_entrega);
create index if not exists historial_tarea_idx on historial (tarea_id);
create index if not exists avisos_cuenta_idx on avisos (cuenta_id);
